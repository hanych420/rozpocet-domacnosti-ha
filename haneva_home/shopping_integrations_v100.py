def _parse_get(endpoint, api_key, params=None):
    response = requests.get(
        f"{PARSE_BASE}/{endpoint}",
        headers={"X-API-Key": api_key, "Accept": "application/json"},
        params=params or {},
        timeout=35,
    )
    response.raise_for_status()
    return response.json()


def _leaflets_from_response(payload):
    out = []
    seen = set()
    for obj in _walk(payload):
        view = obj.get("viewUrl") or obj.get("view_url")
        if not view:
            continue
        view = str(view)
        slug = urlparse(view).path.rstrip("/").split("/")[-1]
        if not slug or slug in seen:
            continue
        seen.add(slug)
        out.append({
            "slug": slug,
            "view_url": view,
            "valid_from": obj.get("validityStartDateFormatted") or obj.get("validityStartDate") or obj.get("valid_from"),
            "valid_to": obj.get("validityEndDateFormatted") or obj.get("validityEndDate") or obj.get("valid_to"),
        })
    return out


def _structured_products(payload, leaflet):
    """Accept product JSON only; never interpret Parse OCR/free text ourselves."""
    products = []
    name_keys = ("productName", "product_name", "name", "title")
    price_keys = ("promoPrice", "salePrice", "currentPrice", "current_price", "price")
    old_keys = ("oldPrice", "originalPrice", "regularPrice", "previousPrice", "old_price")
    amount_keys = ("amount", "packaging", "unit", "size")
    for obj in _walk(payload):
        if not isinstance(obj, dict):
            continue
        # OCR spread/page objects contain text and imageUrl but no explicit product price field.
        name = next((obj.get(k) for k in name_keys if obj.get(k) not in (None, "")), None)
        price_raw = next((obj.get(k) for k in price_keys if obj.get(k) not in (None, "")), None)
        if name is None or price_raw is None:
            continue
        current = core._float_price(price_raw)
        name = core._clean(name)
        if current is None or not name or len(name) < 2:
            continue
        old_raw = next((obj.get(k) for k in old_keys if obj.get(k) not in (None, "")), None)
        old = core._float_price(old_raw)
        products.append({
            "name": name,
            "price_value": current,
            "original_price_value": old,
            "discount_percent": core._discount_percent(current, old, obj.get("discount") or obj.get("discountPercent") or ""),
            "amount": core._clean(next((obj.get(k) for k in amount_keys if obj.get(k)), "")),
            "valid_from": obj.get("valid_from") or obj.get("validFrom") or leaflet.get("valid_from"),
            "valid_to": obj.get("valid_to") or obj.get("validTo") or leaflet.get("valid_to"),
            "source_url": leaflet.get("view_url") or "",
        })
    return products


def _sync_albert_parse():
    api_key = str(_options().get("parse_api_key") or "").strip()
    if not api_key:
        _log("Albert: Parse.bot není nastavený; starý PDF parser ani Kupi už nepoužívám")
        return 0

    current = _parse_get("get_current_leaflets", api_key)
    leaflets = _leaflets_from_response(current)
    if not leaflets:
        raise RuntimeError("Parse.bot nevrátil žádný aktuální Albert leták")

    # Do not burn credits repeatedly on the same published leaflet set.
    slugs = sorted(item["slug"] for item in leaflets[:4])
    slug_fingerprint = hashlib.sha256("|".join(slugs).encode()).hexdigest()
    if _meta_get("parse_albert_leaflets") == slug_fingerprint:
        existing = _count_external("albert")
        _log(f"Albert přes Parse.bot: letáky se nezměnily, ponechávám {existing} uložených nabídek")
        return existing

    deals = []
    for leaflet in leaflets[:4]:
        detail = _parse_get("get_leaflet_detail", api_key, {"id": leaflet["slug"]})
        deals.extend(_structured_products(detail, leaflet))

    _meta_set("parse_albert_leaflets", slug_fingerprint)
    if not deals:
        _log(
            "Albert přes Parse.bot: API funguje, ale veřejný get_leaflet_detail vrací jen OCR stránky, ne strukturované produkty; "
            "Haneva OCR záměrně neparsuje. Je potřeba v Parse.bot doplnit endpoint/fields pro products."
        )
        return 0

    fingerprint = hashlib.sha256(
        json.dumps(deals, ensure_ascii=False, sort_keys=True, default=str).encode("utf-8")
    ).hexdigest()
    count = _replace_store("albert", deals, fingerprint)
    _log(f"Albert přes Parse.bot: {count} strukturovaných nabídek")
    return count


def _sync_once():
    core.init_db()
    _clear_legacy_rows("lidl")
    _clear_legacy_rows("albert")

    counts = {"lidl": _count_external("lidl"), "albert": _count_external("albert")}
    errors = []

    try:
        counts["lidl"] = _sync_lidl_from_ha()
    except Exception as exc:
        message = f"Lidl HA integrace: {type(exc).__name__}: {exc}"
        errors.append(message)
        _log(message)

    try:
        counts["albert"] = _sync_albert_parse()
    except Exception as exc:
        message = f"Albert Parse.bot: {type(exc).__name__}: {exc}"
        errors.append(message)
        _log(message)

    _log(f"hotovo: Lidl={counts['lidl']}, Albert={counts['albert']}, errors={len(errors)}")
    return counts, errors


