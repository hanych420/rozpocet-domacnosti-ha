def _log(message):
    print(f"[Haneva][Akce {VERSION}] {message}", flush=True)


def _now_iso():
    return datetime.now(timezone.utc).isoformat()


def _options():
    try:
        with open("/data/options.json", "r", encoding="utf-8") as fh:
            data = json.load(fh)
            return data if isinstance(data, dict) else {}
    except Exception:
        return {}


def _walk(value):
    if isinstance(value, dict):
        yield value
        for child in value.values():
            yield from _walk(child)
    elif isinstance(value, list):
        for child in value:
            yield from _walk(child)


def _meta_get(key):
    try:
        with core.db() as conn:
            row = conn.execute("SELECT value FROM shopping_sync_meta WHERE key=?", (key,)).fetchone()
        return row["value"] if row else None
    except Exception:
        return None


def _meta_set(key, value):
    with core.db() as conn:
        conn.execute(
            """
            INSERT INTO shopping_sync_meta(key, value, updated_at)
            VALUES(?,?,?)
            ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at
            """,
            (key, str(value), _now_iso()),
        )
        conn.commit()


def _count_external(store):
    with core.db() as conn:
        row = conn.execute(
            "SELECT COUNT(*) AS n FROM official_deals WHERE store=? AND source_kind='official' AND source_fingerprint LIKE ?",
            (store, SOURCE_PREFIX + "%"),
        ).fetchone()
    return int(row["n"] if row else 0)


def _clear_legacy_rows(store):
    """Remove rows generated by our retired HTML/PDF parsers, once."""
    key = f"v100_legacy_cleared_{store}"
    if _meta_get(key) == "1":
        return
    with core.db() as conn:
        conn.execute(
            "DELETE FROM official_deals WHERE store=? AND source_kind='official' AND (source_fingerprint IS NULL OR source_fingerprint NOT LIKE ?)",
            (store, SOURCE_PREFIX + "%"),
        )
        conn.commit()
    _meta_set(key, "1")


def _replace_store(store, deals, fingerprint):
    cleaned = []
    seen = set()
    for deal in deals:
        name = core._clean(deal.get("name"))
        current = core._float_price(deal.get("price_value") or deal.get("price_text"))
        if not name or current is None or current <= 0:
            continue
        valid_from = core._iso_date(deal.get("valid_from"))
        valid_to = core._iso_date(deal.get("valid_to"))
        key = (core._norm(name), round(current, 2), valid_from or "", valid_to or "")
        if key in seen:
            continue
        seen.add(key)
        original = core._float_price(deal.get("original_price_value") or deal.get("original_price"))
        if original is not None and original <= current:
            original = None
        discount = deal.get("discount_percent")
        if discount is None:
            discount = core._discount_percent(current, original, deal.get("discount_text") or "")
        cleaned.append({
            **deal,
            "name": name[:180],
            "price_value": current,
            "price_text": core._fmt_price(current),
            "original_price_value": original,
            "original_price": core._fmt_price(original) if original else "",
            "discount_percent": discount,
            "valid_from": valid_from,
            "valid_to": valid_to,
        })

    if not cleaned:
        return 0

    marker = SOURCE_PREFIX + store + ":" + fingerprint
    now = _now_iso()
    with core.db() as conn:
        conn.execute("DELETE FROM official_deals WHERE store=? AND source_kind='official'", (store,))
        for deal in cleaned[:1800]:
            group_key, group_label = core._group_for(deal["name"])
            conn.execute(
                """
                INSERT INTO official_deals(
                    store, name, name_norm, group_key, group_label,
                    price_text, price_value, original_price, original_price_value,
                    discount_percent, amount, valid_from, valid_to,
                    source_url, source_kind, source_fingerprint, updated_at
                ) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)
                """,
                (
                    store,
                    deal["name"],
                    core._norm(deal["name"]),
                    group_key,
                    group_label,
                    deal["price_text"],
                    deal["price_value"],
                    deal.get("original_price") or "",
                    deal.get("original_price_value"),
                    deal.get("discount_percent"),
                    core._clean(deal.get("amount"))[:100],
                    deal.get("valid_from"),
                    deal.get("valid_to"),
                    core._clean(deal.get("source_url"))[:1000],
                    "official",
                    marker,
                    now,
                ),
            )
        conn.commit()
    return len(cleaned)


# ---------------------------------------------------------------------------
# Lidl: consume an existing Home Assistant integration instead of scraping Lidl.
# Recommended integration: https://github.com/FaserF/ha-lidl
# Its Offers / Offers Preview sensors expose fully structured `discounts` arrays.
# ---------------------------------------------------------------------------


def _ha_states():
    token = os.environ.get("SUPERVISOR_TOKEN", "").strip()
    if not token:
        raise RuntimeError("SUPERVISOR_TOKEN není dostupný")
    response = requests.get(
        HA_STATES_URL,
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        timeout=15,
    )
    response.raise_for_status()
    data = response.json()
    if not isinstance(data, list):
        raise RuntimeError("Home Assistant /states nevrátil seznam")
    return data


def _lidl_sensor_states(states):
    matches = []
    for state in states:
        if not isinstance(state, dict):
            continue
        entity_id = str(state.get("entity_id") or "")
        attrs = state.get("attributes") or {}
        if not entity_id.startswith("sensor.") or not isinstance(attrs, dict):
            continue
        discounts = attrs.get("discounts")
        if not isinstance(discounts, list):
            continue
        # ha-lidl exposes these store fields on both Offers and Offers Preview.
        if str(attrs.get("store_country") or "").upper() != "CZ":
            continue
        if not attrs.get("store_key"):
            continue
        matches.append(state)
    return matches


def _sync_lidl_from_ha():
    states = _ha_states()
    sensors = _lidl_sensor_states(states)
    if not sensors:
        raise RuntimeError(
            "nenašel jsem senzory Lidl Weekly Offers v Home Assistantu; nainstaluj a nastav integraci FaserF/ha-lidl pro CZ"
        )

    deals = []
    fingerprint_rows = []
    sensor_names = []
    for state in sensors:
        attrs = state.get("attributes") or {}
        sensor_names.append(state.get("entity_id") or "")
        discounts = attrs.get("discounts") or []
        for offer in discounts:
            if not isinstance(offer, dict):
                continue
            name = core._clean(offer.get("title") or offer.get("name") or "")
            current = core._float_price(offer.get("price"))
            if not name or current is None:
                continue
            old = core._float_price(offer.get("old_price"))
            discount_text = core._clean(offer.get("discount"))
            deals.append({
                "name": name,
                "price_value": current,
                "original_price_value": old,
                "discount_percent": core._discount_percent(current, old, discount_text),
                "discount_text": discount_text,
                "amount": core._clean(offer.get("packaging") or offer.get("price_per_unit") or ""),
                "valid_from": offer.get("start_date"),
                "valid_to": offer.get("end_date"),
                "source_url": "",
            })
            fingerprint_rows.append({
                "id": offer.get("id"),
                "title": name,
                "price": offer.get("price"),
                "old_price": offer.get("old_price"),
                "start": offer.get("start_date"),
                "end": offer.get("end_date"),
            })

    if not deals:
        raise RuntimeError("Lidl integrace je nalezená, ale její Offers senzory zatím neobsahují žádné nabídky")

    fingerprint = hashlib.sha256(
        json.dumps(fingerprint_rows, ensure_ascii=False, sort_keys=True, default=str).encode("utf-8")
    ).hexdigest()
    count = _replace_store("lidl", deals, fingerprint)
    _log(f"Lidl přes Home Assistant: {count} nabídek ze {len(sensors)} senzorů ({', '.join(sensor_names)})")
    return count


